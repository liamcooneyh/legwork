"""Configuration: config.yaml for behaviour, environment variables for secrets and paths."""

from __future__ import annotations

import os
from functools import lru_cache
from pathlib import Path

import yaml
from pydantic import BaseModel, Field

ROOT = Path(__file__).resolve().parent.parent


class Boards(BaseModel):
    greenhouse: list[str] = Field(default_factory=list)
    lever: list[str] = Field(default_factory=list)
    ashby: list[str] = Field(default_factory=list)


class LinkedInAlertsConfig(BaseModel):
    enabled: bool = True
    # Gmail search syntax. Searches all mail, so archived or labelled alerts are still found.
    query: str = "from:jobalerts-noreply@linkedin.com newer_than:14d"
    max_emails: int = 150
    # Company name -> "greenhouse:token", "lever:token", "ashby:token", or "none" to stop probing.
    company_overrides: dict[str, str] = Field(default_factory=dict)
    title_match_threshold: float = 0.85
    # Start polling a company's board once one of its jobs shows up in an alert.
    watch_matched_companies: bool = True
    reprobe_misses_after_days: int = 30


class SearchConfig(BaseModel):
    boards: Boards = Field(default_factory=Boards)
    boards_file: str = "boards.yaml"   # generated by `autoapply build-boards`
    linkedin_alerts: LinkedInAlertsConfig = Field(default_factory=LinkedInAlertsConfig)
    title_include: list[str] = Field(default_factory=list)
    title_exclude: list[str] = Field(default_factory=list)
    locations: list[str] = Field(default_factory=list)
    allow_remote: bool = True
    location_exclude: list[str] = Field(default_factory=list)
    exclude_companies: list[str] = Field(default_factory=list)
    max_age_days: int = 30
    preferences: str = ""


class MatchingConfig(BaseModel):
    min_score: int = 70
    max_scored_per_cycle: int = 2000


class ApplyConfig(BaseModel):
    # approve: prepare each application and wait for you to click Approve & submit.
    # auto: submit matches automatically. Switch on the dashboard's Settings page.
    mode: str = "approve"
    max_per_day: int = 15
    max_per_company: int = 2
    company_window_days: int = 30
    delay_seconds: tuple[int, int] = (45, 150)
    auto_accept_required_consents: bool = True
    cover_letter: str = "when_asked"  # always | when_asked | never
    tailor_resume: bool = True
    paper: str = "Letter"
    headless: bool = True
    page_timeout_seconds: int = 45


class ReplyTrackingConfig(BaseModel):
    enabled: bool = True
    interval_minutes: int = 30       # how often Gmail is checked for replies
    lookback_days: int = 21          # how far back each check searches
    max_emails: int = 50
    track_days: int = 120            # only match replies to applications this recent
    no_response_days: int = 30       # mark "No response" after this many quiet days (0 = never)


class ScheduleConfig(BaseModel):
    enabled: bool = True
    interval_hours: float = 4


class LLMConfig(BaseModel):
    model: str = "claude-sonnet-5-5"          # writing: resume tailoring, fact-checks, cover letters, answers
    scoring_model: str = "claude-haiku-5-5"   # fit scoring (most calls)


class Config(BaseModel):
    search: SearchConfig = Field(default_factory=SearchConfig)
    matching: MatchingConfig = Field(default_factory=MatchingConfig)
    apply: ApplyConfig = Field(default_factory=ApplyConfig)
    schedule: ScheduleConfig = Field(default_factory=ScheduleConfig)
    replies: ReplyTrackingConfig = Field(default_factory=ReplyTrackingConfig)
    llm: LLMConfig = Field(default_factory=LLMConfig)


class Env:
    """Paths and secrets resolved from the environment."""

    @property
    def data_dir(self) -> Path:
        path = Path(os.environ.get("DATA_DIR", ROOT / "data"))
        path.mkdir(parents=True, exist_ok=True)
        return path

    @property
    def db_path(self) -> Path:
        return self.data_dir / "autoapply.db"

    @property
    def artifacts_dir(self) -> Path:
        path = self.data_dir / "artifacts"
        path.mkdir(parents=True, exist_ok=True)
        return path

    @property
    def config_path(self) -> Path:
        return Path(os.environ.get("CONFIG_PATH", ROOT / "config.yaml"))

    @property
    def profile_path(self) -> Path:
        return Path(os.environ.get("PROFILE_PATH", ROOT / "profile" / "profile.yaml"))

    @property
    def dashboard_user(self) -> str:
        return os.environ.get("DASHBOARD_USER", "admin")

    @property
    def dashboard_password(self) -> str | None:
        return os.environ.get("DASHBOARD_PASSWORD") or None

    @property
    def notify_url(self) -> str | None:
        return os.environ.get("NOTIFY_URL") or None

    # LinkedIn alert email access: Gmail API (OAuth refresh token) or IMAP (app password).
    @property
    def gmail_oauth(self) -> tuple[str, str, str] | None:
        vals = tuple(os.environ.get(k, "") for k in ("GMAIL_CLIENT_ID", "GMAIL_CLIENT_SECRET", "GMAIL_REFRESH_TOKEN"))
        return vals if all(vals) else None  # type: ignore[return-value]

    @property
    def imap(self) -> tuple[str, str, str] | None:
        user, password = os.environ.get("IMAP_USER", ""), os.environ.get("IMAP_PASSWORD", "")
        return (os.environ.get("IMAP_HOST", "imap.gmail.com"), user, password) if user and password else None

    @property
    def port(self) -> int:
        return int(os.environ.get("PORT", "8080"))


env = Env()


def load_dotenv(path: Path = ROOT / ".env") -> None:
    """Load KEY=value lines from .env for local runs. Real environment variables win."""
    if not path.exists():
        return
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        os.environ.setdefault(key.strip(), value.strip().strip('"').strip("'"))


@lru_cache(maxsize=1)
def load_config() -> Config:
    path = env.config_path
    if not path.exists():
        return Config()
    with path.open() as f:
        return Config.model_validate(yaml.safe_load(f) or {})
