def cmd_apply(args) -> None:
    from playwright.sync_api import sync_playwright

    from . import db
    from .pipeline import Pipeline
    from .sources import FETCHERS, detect_from_url

    db.init()
    found = detect_from_url(args.url)
    if not found:
        sys.exit("Not a Greenhouse, Lever, or Ashby job URL.")
    ats, board, external_id = found
    job = next((j for j in FETCHERS[ats](board) if j.external_id == external_id), None)
    if job is None:
        sys.exit(f"Job {external_id} not found on {ats}:{board} (closed?).")
    db.upsert_job(job.to_row())
    pipeline = Pipeline()
    with sync_playwright() as pw:
        browser = pw.chromium.launch(headless=not args.headed)
        try:
            outcome = pipeline.apply_one(browser, dict(db.get_job(job.id)), dry_run=not args.live)
        finally:
            browser.close()
    print(json.dumps({"status": outcome.status, "detail": outcome.detail, "answers": outcome.answers}, indent=1))


