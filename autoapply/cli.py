def cmd_build_boards(args) -> None:
    """Check every company in companies.txt against the three ATS APIs and write boards.yaml."""
    from concurrent.futures import ThreadPoolExecutor

    from .settings import ROOT
    from .sources import FETCHERS
    from .sources.resolve import company_key, slug_variants

    names = [l.strip() for l in Path(args.companies).read_text().splitlines() if l.strip() and not l.startswith("#")]
    names = list({company_key(n): n for n in names}.values())

    def name_ok(name: str, jobs) -> bool:
        want = company_key(name)
        listed = {j.company for j in jobs if j.ats == "greenhouse"}
        if listed:  # Greenhouse reports the employer's name
            return any(want in company_key(n) or company_key(n) in want for n in listed)
        # Lever/Ashby don't, so the company must name itself in its own job descriptions.
        core = company_key(" ".join(w for w in name.split() if w.lower().strip(",.") not in
                                    {"inc", "llc", "ltd", "corp", "co", "the", "technologies", "labs", "ai", "hq"}))
        texts = [company_key(j.description[:3000]) for j in jobs[:8]]
        return any(core and core in t for t in texts)

    def probe(name: str):
        for slug in slug_variants(name):
            for ats, fetch in FETCHERS.items():
                try:
                    jobs = fetch(slug)
                except Exception:
                    continue
                if jobs and name_ok(name, jobs):
                    return name, ats, slug, len(jobs)
        return name, None, None, 0

    with ThreadPoolExecutor(max_workers=12) as pool:
        results = list(pool.map(probe, names))
    found = sorted((r for r in results if r[1]), key=lambda r: (r[1], r[2]))
    missing = sorted(r[0] for r in results if not r[1])
    lines = ["# Generated by `autoapply build-boards` from companies.txt. Safe to edit.", ""]
    for ats in FETCHERS:
        lines.append(f"{ats}:")
        lines += [f"  - {slug:<28} # {name} ({n} jobs)" for name, a, slug, n in found if a == ats]
        lines.append("")
    lines.append("# Not found on Greenhouse/Lever/Ashby (other ATS, or the board name differs):")
    lines += [f"#   {m}" for m in missing]
    out = Path(args.out) if args.out else ROOT / "boards.yaml"
    out.write_text("\n".join(lines) + "\n")
    print(f"{len(found)} of {len(names)} companies found ({sum(r[3] for r in found)} open jobs). Wrote {out}.")


