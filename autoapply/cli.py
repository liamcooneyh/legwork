def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(prog="autoapply", description="Automatic job applications from company ATS boards.")
    sub = parser.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("serve", help="dashboard + scheduler (what runs on Fly)")
    p.add_argument("--host", default="0.0.0.0")
    p.add_argument("--port", type=int)
    p.set_defaults(fn=cmd_serve)

    p = sub.add_parser("run-once", help="run one full cycle now")
    mode = p.add_mutually_exclusive_group()
    mode.add_argument("--auto", action="store_true", help="switch to automatic submitting (sticks until changed)")
    mode.add_argument("--approve", action="store_true", help="switch to prepare-and-wait-for-approval (sticks)")
    p.add_argument("--no-apply", action="store_true", help="discover and score only")
    p.set_defaults(fn=cmd_run_once)

    p = sub.add_parser("discover", help="fetch boards + LinkedIn alerts and prefilter, no Claude calls")
    p.add_argument("--show", type=int, default=40)
    p.set_defaults(fn=cmd_discover)

    p = sub.add_parser("check-boards", help="confirm every configured board token resolves")
    p.set_defaults(fn=cmd_check_boards)

    p = sub.add_parser("replies", help="check Gmail for replies about your applications now")
    p.set_defaults(fn=cmd_replies)

    p = sub.add_parser("screen-check", help="dry-run the AI title screen against known-good jobs (changes nothing)")
    p.add_argument("--sample", type=int, default=400, help="how many other titles to mix in")
    p.add_argument("--title", action="append", help="an extra title that must be kept (repeatable)")
    p.set_defaults(fn=cmd_screen_check)

    p = sub.add_parser("linkedin-reset", help="clear entries made by the old LinkedIn reader (dry run unless --yes)")
    p.add_argument("--yes", action="store_true")
    p.set_defaults(fn=cmd_linkedin_reset)

    p = sub.add_parser("backup", help="back up the database and profile to Google Drive now")
    p.set_defaults(fn=cmd_backup)

    p = sub.add_parser("notify-test", help="send a test phone notification to NOTIFY_URL")
    p.set_defaults(fn=cmd_notify_test)

    p = sub.add_parser("build-boards", help="find companies.txt companies on Greenhouse/Lever/Ashby → boards.yaml")
    p.add_argument("--companies", default="companies.txt")
    p.add_argument("--out")
    p.set_defaults(fn=cmd_build_boards)

    p = sub.add_parser("apply", help="prepare one job URL for approval (or submit with --live)")
    p.add_argument("url")
    p.add_argument("--live", action="store_true")
    p.add_argument("--headed", action="store_true", help="show the browser window")
    p.set_defaults(fn=cmd_apply)

    p = sub.add_parser("linkedin", help="ingest LinkedIn alert emails now, or --parse a saved email")
    p.add_argument("--parse", metavar="FILE", help="parse a saved .html or .txt alert email and print the jobs")
    p.set_defaults(fn=cmd_linkedin)

    p = sub.add_parser("import-resume", help="draft profile.yaml from a resume PDF with Claude")
    p.add_argument("pdf")
    p.add_argument("--out")
    p.add_argument("--force", action="store_true", help="overwrite an existing profile.yaml")
    p.set_defaults(fn=cmd_import_resume)

    p = sub.add_parser("render-resume", help="render the untailored master resume to PDF")
    p.add_argument("--out", default="master_resume.pdf")
    p.set_defaults(fn=cmd_render_resume)

    p = sub.add_parser("build-extension", help="refresh the Chrome extension's copy of the form reader")
    p.set_defaults(fn=cmd_build_extension)

    p = sub.add_parser("helper", help="on your Mac: open drafts pre-filled for you to review and submit")
    p.add_argument("--install", action="store_true", help="start the helper automatically at login")
    p.add_argument("--uninstall", action="store_true", help="stop starting it at login")
    p.set_defaults(fn=cmd_helper)

    p = sub.add_parser("google-auth", help="one-time Google sign-in for Drive copies (or the Gmail API)")
    p.add_argument("service", choices=sorted(GOOGLE_SCOPES), help="drive: copy sent resumes to Drive; gmail: Gmail API")
    p.add_argument("--client-id", help="OAuth client ID (asked for if omitted)")
    p.add_argument("--port", type=int, default=0, help="local port for Google's redirect (default: any free port)")
    p.set_defaults(fn=cmd_google_auth)

    args = parser.parse_args(argv)
    from .settings import load_dotenv

    load_dotenv()
    args.fn(args)


if __name__ == "__main__":
    main()
