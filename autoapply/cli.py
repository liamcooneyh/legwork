GOOGLE_SCOPES = {
    "drive": ("https://www.googleapis.com/auth/drive.file", "GDRIVE",
              "create and update only the files this app makes in your Drive"),
    "gmail": ("https://www.googleapis.com/auth/gmail.readonly", "GMAIL", "read (not change) your Gmail"),
}


def _set_env_values(path: Path, values: dict[str, str]) -> None:
    lines = path.read_text().splitlines() if path.exists() else []
    for key, value in values.items():
        new = f"{key}={value}"
        for i, line in enumerate(lines):
            if line.startswith(f"{key}="):
                lines[i] = new
                break
        else:
            lines.append(new)
    path.write_text("\n".join(lines) + "\n")


def cmd_google_auth(args) -> None:
    """One-time Google sign-in for the server. Saves the result to .env; nothing secret is printed."""
    import getpass
    import webbrowser

    from .settings import ROOT

    scope, prefix, what = GOOGLE_SCOPES[args.service]
    client_id = args.client_id or input("OAuth client ID: ").strip()
    client_secret = ""
    while not client_secret:
        client_secret = getpass.getpass("OAuth client secret (hidden, paste then press Enter): ").strip()
        if not client_secret:
            print("  Nothing was received. Paste with Cmd+V (it stays invisible), then press Enter.")
        elif not client_secret.startswith("GOCSPX-"):
            print(f"  Got {len(client_secret)} characters, but client secrets start with GOCSPX-. Try again.")
            client_secret = ""
        else:
            print(f"  Got it ({len(client_secret)} characters).")
    result: dict[str, str] = {}

    class Handler(http.server.BaseHTTPRequestHandler):
        def do_GET(self):
            query = urllib.parse.parse_qs(urllib.parse.urlparse(self.path).query)
            result.update({k: v[0] for k, v in query.items()})
            self.send_response(200)
            self.end_headers()
            self.wfile.write(b"Done. You can close this tab and go back to the terminal.")

        def log_message(self, *a):
            pass

    # Port 0 = any free port; Google accepts any loopback port for desktop clients.
    server = http.server.HTTPServer(("127.0.0.1", args.port), Handler)
    server.timeout = 300
    redirect = f"http://127.0.0.1:{server.server_address[1]}"
    auth_url = "https://accounts.google.com/o/oauth2/v2/auth?" + urllib.parse.urlencode({
        "client_id": client_id, "redirect_uri": redirect, "response_type": "code",
        "scope": scope, "access_type": "offline", "prompt": "consent",
    })
    print(f"\nOpening Google sign-in. You'll be asked to let this app {what}.")
    print("If no browser window opens, visit:\n\n" + auth_url + "\n")
    try:
        webbrowser.open(auth_url)
    except Exception:
        pass
    with server:
        server.handle_request()  # waits up to 5 minutes for Google to redirect back
    if "code" not in result:
        sys.exit(f"Sign-in didn't complete: {result.get('error', 'timed out or no code returned')}")
    resp = httpx.post("https://oauth2.googleapis.com/token", data={
        "code": result["code"], "client_id": client_id, "client_secret": client_secret,
        "redirect_uri": redirect, "grant_type": "authorization_code",
    }, timeout=30)
    token = resp.json().get("refresh_token")
    if not token:
        sys.exit(f"Google didn't return a refresh token: {resp.text[:300]}")
    env_file = ROOT / ".env"
    _set_env_values(env_file, {f"{prefix}_CLIENT_ID": client_id, f"{prefix}_CLIENT_SECRET": client_secret,
                               f"{prefix}_REFRESH_TOKEN": token})
    print(f"Signed in. Saved {prefix}_CLIENT_ID / _CLIENT_SECRET / _REFRESH_TOKEN to {env_file}.")
    print("\nNow copy them to the server (values are read from .env, not shown):\n")
    m = re.search(r'^app\s*=\s*"([^"]+)"', (ROOT / "fly.toml").read_text(), re.M) if (ROOT / "fly.toml").exists() else None
    print(f"  grep -E '^{prefix}_' {env_file} | fly secrets import -a {m.group(1) if m else '<your-fly-app>'}\n")


