def cmd_screen_check(args) -> None:
    """Dry run of the AI title screen: known-good jobs must all be kept. Changes nothing."""
    import random

    from . import db
    from .filters import prefilter
    from .pipeline import Pipeline

    db.init()
    p = Pipeline(log=lambda m: None)
    if p.llm is None:
        sys.exit("ANTHROPIC_API_KEY not set")
    with db.connect() as conn:
        good = [dict(r) for r in conn.execute(
            "SELECT * FROM jobs WHERE (score >= 70 OR status IN ('ready','needs_manual','matched','applied','submitting')) "
            "AND ats != 'linkedin'")]
        pool = [dict(r) for r in conn.execute(
            "SELECT * FROM jobs WHERE status IN ('filtered_out','screen','screened_out','prefiltered','rejected') "
            "AND ats != 'linkedin'")]
    good += [{"id": f"extra:{i}", "title": t, "company": co, "department": "", "location": loc}
             for i, (t, co, loc) in enumerate([
                 ("GTM Operations Lead", "Trading Technologies", "New York, NY (Hybrid)"),
                 ("Solutions Experience Engineer", "Gong", "New York, NY"),
                 *[(t, "Example Co", "New York, NY") for t in args.title or []]])]
    good_ids = {g["id"] for g in good}
    eligible = [r for r in pool if r["id"] not in good_ids and not prefilter(r, p.cfg.search)]
    random.seed(7)
    sample = random.sample(eligible, min(args.sample, len(eligible)))
    batch = good + sample
    random.shuffle(batch)
    snapshot = p.llm.candidate_snapshot(p.cfg.search.preferences)
    examples = db.kv_json("screen_examples", [])
    kept_ids = set()
    for start in range(0, len(batch), 120):
        part = batch[start:start + 120]
        kept_ids |= {part[i]["id"] for i in p.llm.screen_titles(part, snapshot, examples)}
    dropped_good = [g for g in good if g["id"] not in kept_ids]
    kept_sample = [r for r in sample if r["id"] in kept_ids]
    print(f"Known-good jobs kept: {len(good) - len(dropped_good)} / {len(good)}")
    for g in dropped_good:
        print(f"  DROPPED: {g['title']} — {g['company']}")
    print(f"Other titles kept: {len(kept_sample)} / {len(sample)} ({100 * len(kept_sample) // max(1, len(sample))}%)")
    print("  examples kept:", "; ".join(r["title"] for r in kept_sample[:15]))
    print("  examples dropped:", "; ".join([r["title"] for r in sample if r["id"] not in kept_ids][:15]))
    print(f"Claude cost for this check ≈ ${p.llm.cost_usd():.3f}")
    if dropped_good:
        sys.exit(1)


def cmd_linkedin_reset(args) -> None:
    """Undo what the old (buggy) LinkedIn reader created, so alerts are re-read correctly.
    Never touches jobs you've applied to or that are prepared."""
    from . import db
    from .settings import load_config
    from .sources import board_list

    db.init()
    keep_status = (db.APPLIED, db.READY, db.SUBMITTING)
    with db.connect() as conn:
        manual = conn.execute("SELECT id, title, company FROM jobs WHERE ats='linkedin' AND status NOT IN (?,?,?)",
                              keep_status).fetchall()
        guesses = conn.execute("SELECT company_key, company, ats, board FROM company_boards").fetchall()
    search = load_config().search
    no_learning = search.model_copy(update={"linkedin_alerts": search.linkedin_alerts.model_copy(
        update={"watch_matched_companies": False})})
    configured = {f"{a}:{b}" for a, b in board_list(no_learning)}  # config.yaml, boards.yaml, added in dashboard
    learned_only = {f"{g['ats']}:{g['board']}" for g in guesses if g["ats"]} - configured
    with db.connect() as conn:
        stray = [r for r in conn.execute("SELECT id, title, company, ats, board, status FROM jobs WHERE status NOT IN (?,?,?)",
                                         keep_status) if f"{r['ats']}:{r['board']}" in learned_only]
        relinked = conn.execute("SELECT COUNT(*) FROM jobs WHERE linkedin_id IS NOT NULL AND ats != 'linkedin'").fetchone()[0]
    print(f"LinkedIn 'apply yourself' entries to remove: {len(manual)}")
    for r in manual:
        print(f"   {r['title'][:60]} | {r['company'][:40]}")
    print(f"Company→board guesses to forget: {len(guesses)}")
    for g in guesses:
        print(f"   {g['company'][:50]} → {g['ats'] or 'no board'}:{g['board'] or ''}")
    print(f"Jobs from boards only known through those guesses (removed): {len(stray)}")
    for r in stray[:20]:
        print(f"   {r['ats']}:{r['board']} | {r['title'][:60]}")
    print(f"Board jobs whose LinkedIn link is cleared: {relinked}")
    if not args.yes:
        print("\nDry run. Re-run with --yes to apply.")
        return
    with db.connect() as conn:
        conn.executemany("DELETE FROM jobs WHERE id=?", [(r["id"],) for r in manual + stray])
        conn.execute("DELETE FROM company_boards")
        conn.execute("UPDATE jobs SET linkedin_id=NULL, linkedin_url=NULL WHERE ats != 'linkedin'")
    print("Done. The next run re-reads the last 14 days of alerts with the fixed reader.")


